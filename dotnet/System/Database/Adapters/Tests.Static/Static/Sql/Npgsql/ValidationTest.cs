namespace Allors.Database.Adapters.Sql.Npgsql
{
    using System;
    using System.Collections.Generic;
    using global::Npgsql;
    using Meta;
    using NpgsqlTypes;
    using Xunit;
    using C1 = Domain.C1;
    using ObjectFactory = ObjectFactory;

    // The validation reads a schema from the catalogue of PostgreSQL: whether it exists, and its tables with
    // their columns. What it reads is what the views schemata, tables and columns of information_schema show.
    public class ValidationTest : IClassFixture<Fixture<ValidationTest>>, IDisposable
    {
        // The same read through the views.
        private const string SchemaThroughTheViews = @"
SELECT  count(schema_name)
FROM    information_schema.schemata
WHERE   schema_name = @schemaName";

        private const string TablesThroughTheViews = @"
SELECT T.table_name,
       C.column_name,
       C.data_type,
       C.character_maximum_length,
       C.numeric_precision,
       C.numeric_scale
FROM information_schema.tables AS T
FULL OUTER JOIN information_schema.columns AS C
ON T.table_name = C.table_name
WHERE T.table_type = 'BASE TABLE'
AND T.table_schema = @tableSchema
AND C.table_schema = @tableSchema";

        // What a schema can hold next to the tables of the adapter.
        private static readonly string[] CreateAwkward =
        {
            "CREATE SCHEMA awkward",
            "CREATE DOMAIN awkward.d_bigint AS bigint",
            "CREATE DOMAIN awkward.d_varchar AS varchar(10)",
            "CREATE DOMAIN awkward.d_numeric AS numeric(12,3)",
            "CREATE DOMAIN awkward.d_domain AS awkward.d_bigint",
            "CREATE DOMAIN awkward.d_array AS bigint[]",
            "CREATE TYPE awkward.colour AS ENUM ('red', 'green')",
            "CREATE TYPE awkward.pair AS (a bigint, b uuid)",

            // The types of the adapter and their neighbours, and a column with an identity, a collation, a
            // default and a generated value.
            @"CREATE TABLE awkward.plain (
                o bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, c uuid, s256 varchar(256), s varchar,
                t text COLLATE ""C"", i integer DEFAULT 1, n numeric(19,2), n0 numeric, f double precision,
                b boolean, d timestamp, d3 timestamp(3), dz timestamp with time zone, bin bytea, sm smallint,
                r real, ch char(5), bt bit(3), vb bit varying(5), g bigint GENERATED ALWAYS AS (i * 2) STORED)",

            // Columns of a domain, of an array and of a type that somebody created.
            @"CREATE TABLE awkward.typed (
                o bigint, db awkward.d_bigint, dv awkward.d_varchar, dn awkward.d_numeric, dd awkward.d_domain,
                da awkward.d_array, arr bigint[], arrv varchar(5)[], en awkward.colour, p awkward.pair)",

            // A column that was dropped, and a table that has no column.
            "CREATE TABLE awkward.dropped (o bigint, gone integer)",
            "ALTER TABLE awkward.dropped DROP COLUMN gone",
            "CREATE TABLE awkward.nocolumns ()",

            // Tables of another kind, and names in another case.
            "CREATE TABLE awkward.parted (o bigint, c uuid) PARTITION BY RANGE (o)",
            "CREATE TABLE awkward.parted_1 PARTITION OF awkward.parted FOR VALUES FROM (0) TO (1000)",
            "CREATE TABLE awkward.child (extra integer) INHERITS (awkward.dropped)",
            "CREATE TABLE awkward.oftype OF awkward.pair",
            "CREATE UNLOGGED TABLE awkward.unlogged (o bigint)",
            "CREATE TABLE awkward.\"MixedCase\" (\"O\" bigint, \"c\" uuid)",

            // What has columns and is no table.
            "CREATE VIEW awkward.aview AS SELECT o, c FROM awkward.plain",
            "CREATE MATERIALIZED VIEW awkward.amatview AS SELECT o, c FROM awkward.plain",
            "CREATE SEQUENCE awkward.asequence",
        };

        private readonly Profile profile;

        private readonly string connectionString;

        public ValidationTest()
        {
            this.profile = new Profile(this.GetType().Name);
            this.connectionString = Provisioning.ConnectionString(this.GetType().Name);
        }

        public void Dispose() => this.profile.Dispose();

        [Fact]
        public void TheTablesOfTheAdapterAreReadAsTheViewsShowThem()
        {
            this.profile.CreateDatabase().Init();

            var schema = Read(this.connectionString, "allors");

            Assert.True(schema.Exists);
            Assert.NotEmpty(schema.TableByName);
        }

        [Fact]
        public void WhatASchemaCanHoldIsReadAsTheViewsShowIt()
        {
            this.profile.ExecuteScalar("DROP SCHEMA IF EXISTS awkward CASCADE");
            try
            {
                foreach (var statement in CreateAwkward)
                {
                    this.profile.ExecuteScalar(statement);
                }

                var schema = Read(this.connectionString, "awkward");

                // The tables that have a column.
                Assert.Equal(9, schema.TableByName.Count);
            }
            finally
            {
                this.profile.ExecuteScalar("DROP SCHEMA IF EXISTS awkward CASCADE");
            }
        }

        // The tables of pg_catalog belong to another role, which lets every login read most of them. A login
        // that is no superuser may not read pg_authid, and of pg_subscription not the column subconninfo: the
        // views do not show what the login may not touch.
        [Fact]
        public void TablesOfAnotherOwnerAreReadAsTheViewsShowThem()
        {
            var schema = Read(this.ConnectionStringOfNoSuperuser(), "pg_catalog");

            Assert.NotNull(schema.GetTable("pg_catalog.pg_class"));
            Assert.Null(schema.GetTable("pg_catalog.pg_authid"));

            var subscription = schema.GetTable("pg_catalog.pg_subscription");
            Assert.NotNull(subscription);
            Assert.NotNull(subscription.GetColumn("subname"));
            Assert.Null(subscription.GetColumn("subconninfo"));
        }

        // A login that is no superuser may not use the schema pg_toast: the views do not show it.
        [Theory]
        [InlineData("pg_toast")]
        [InlineData("no_such_schema")]
        public void ASchemaThatTheLoginMayNotUseOrThatIsMissingIsReadAsTheViewsShowIt(string schemaName)
        {
            var schema = Read(this.ConnectionStringOfNoSuperuser(), schemaName);

            Assert.False(schema.Exists);
            Assert.Empty(schema.TableByName);
        }

        // A temporary table is in a schema of its session: the views do not show the temporary tables of
        // another session.
        [Fact]
        public void TheTemporaryTablesOfAnotherSessionAreReadAsTheViewsShowThem()
        {
            using (var connection = new NpgsqlConnection(this.connectionString))
            {
                connection.Open();

                using (var command = new NpgsqlCommand("CREATE TEMPORARY TABLE held (o bigint)", connection))
                {
                    command.ExecuteNonQuery();
                }

                string schemaName;
                using (var command = new NpgsqlCommand("SELECT nspname::text FROM pg_namespace WHERE oid = pg_my_temp_schema()", connection))
                {
                    schemaName = (string)command.ExecuteScalar();
                }

                var schema = Read(this.connectionString, schemaName);

                Assert.Empty(schema.TableByName);
            }
        }

        // The schema as the validation reads it over a connection, once it is what the views show over it.
        private static Schema Read(string connectionString, string schemaName)
        {
            var database = new Database(new DefaultDomainDatabaseServices(), new Configuration
            {
                ObjectFactory = new ObjectFactory(new MetaBuilder().Build(), typeof(C1)),
                ConnectionString = connectionString,
                SchemaName = schemaName,
            });

            var schema = new Schema(database);

            var read = new List<string>();
            foreach (var table in schema.TableByName.Values)
            {
                foreach (var column in table.ColumnByLowercaseColumnName.Values)
                {
                    read.Add(Line(table.Name, column.Name, column.DataType, column.CharacterMaximumLength, column.NumericPrecision, column.NumericScale));
                }
            }

            bool exists;
            var shown = new List<string>();
            using (var connection = new NpgsqlConnection(database.ConnectionString))
            {
                connection.Open();

                using (var command = new NpgsqlCommand(SchemaThroughTheViews, connection))
                {
                    command.Parameters.Add("@schemaName", NpgsqlDbType.Varchar).Value = schemaName;
                    exists = (long)command.ExecuteScalar() != 0;
                }

                using (var command = new NpgsqlCommand(TablesThroughTheViews, connection))
                {
                    command.Parameters.Add("@tableSchema", NpgsqlDbType.Varchar).Value = schemaName;
                    using (var reader = command.ExecuteReader())
                    {
                        while (reader.Read())
                        {
                            shown.Add(Line(schemaName + "." + reader.GetString(0), reader.GetString(1), reader.GetString(2), reader.GetValue(3), reader.GetValue(4), reader.GetValue(5)));
                        }
                    }
                }
            }

            read.Sort(StringComparer.Ordinal);
            shown.Sort(StringComparer.Ordinal);

            Assert.Equal(shown, read);
            Assert.Equal(exists, schema.Exists);

            return schema;
        }

        private static string Line(string table, string column, string dataType, object characterMaximumLength, object numericPrecision, object numericScale) =>
            string.Join("|", Name(table), Name(column), dataType.Trim().ToLowerInvariant(), characterMaximumLength, numericPrecision, numericScale);

        // The adapter writes a name in lower case, and a reserved word between quotes.
        private static string Name(string name) => name.Replace("\"", string.Empty).ToLowerInvariant();

        // A superuser may touch everything. A login that is one connects as pg_signal_backend, a role that every
        // server has and that is given nothing to read.
        private string ConnectionStringOfNoSuperuser() =>
            (bool)this.profile.ExecuteScalar("SELECT rolsuper FROM pg_roles WHERE rolname = current_user")
                ? new NpgsqlConnectionStringBuilder(this.connectionString) { Options = "-c role=pg_signal_backend" }.ConnectionString
                : this.connectionString;
    }
}
